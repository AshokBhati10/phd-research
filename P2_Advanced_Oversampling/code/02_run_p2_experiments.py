"""STEP 2 -- Run Person 2 experiments on the frozen corrected-scope test set.

Techniques (train-only resampling):
  Borderline-SMOTE  (full 1,837,734-row train split)
  KMeans-SMOTE      (full train split; documented non-default params)
  SVM-SMOTE         (shared stratified 50k train subsample -- O(n^2))
  SMOTE-N           (same shared 50k train subsample -- O(n^2) memory)
Plus a self-contained No-Balancing baseline (P1's corrected baseline also exists).

Usage:
  python 02_run_p2_experiments.py --pilot --determinism   # resampling determinism check
  python 02_run_p2_experiments.py --pilot                 # pilot end-to-end (pilot/, never results/)
  python 02_run_p2_experiments.py                         # full run, checkpoint/resume
  python 02_run_p2_experiments.py --force                 # redo everything
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C

PILOT_ROWS = 100_000
PILOT_TRAIN = 80_000

# Techniques executed on the shared stratified 50k train subsample (O(n^2) cost/memory)
SUBSAMPLE_TECHNIQUES = {"SVM-SMOTE", "SMOTE-N"}


def load_data(pilot):
    """Return Xtr, ytr, Xte, yte, fingerprint, splits_note."""
    from sklearn.model_selection import train_test_split as tts

    X_train = pd.read_parquet(C.P1_SPLITS / "X_train.parquet")
    X_test = pd.read_parquet(C.P1_SPLITS / "X_test.parquet")
    y_train = pd.read_parquet(C.P1_SPLITS / "y_train.parquet")["y"].astype(np.int64)
    y_test = pd.read_parquet(C.P1_SPLITS / "y_test.parquet")["y"].astype(np.int64)

    if not pilot:
        fp = C.fingerprint(X_test.values, y_test.values)
        if fp != C.EXPECTED_TEST_FINGERPRINT:
            raise SystemExit(f"TEST FINGERPRINT MISMATCH: {fp}")
        return X_train, y_train, X_test, y_test, fp, "full corrected 2015-2024 split"

    # Pilot: stratified 100k analytical sample from the train split, then 80/20.
    Xp, _, yp, _ = tts(X_train, y_train, train_size=PILOT_ROWS,
                       stratify=y_train, random_state=C.RNG)
    Xp, yp = Xp.reset_index(drop=True), yp.reset_index(drop=True)
    Xtr, Xte, ytr, yte = tts(Xp, yp, train_size=PILOT_TRAIN, stratify=yp,
                             random_state=C.RNG)
    Xtr, Xte = Xtr.reset_index(drop=True), Xte.reset_index(drop=True)
    ytr, yte = ytr.reset_index(drop=True), yte.reset_index(drop=True)
    fp = C.fingerprint(Xte.values, yte.values)
    return Xtr, ytr, Xte, yte, fp, "PILOT 100k sample -> 80k/20k stratified split"


def verify_on_disk_fingerprint():
    X_test = pd.read_parquet(C.P1_SPLITS / "X_test.parquet")
    y_test = pd.read_parquet(C.P1_SPLITS / "y_test.parquet")["y"].astype(np.int64)
    return C.fingerprint(X_test.values, y_test.values)


def run_technique(technique, Xtr, ytr, Xte, yte, out, results_csv, force):
    """Resample once, train/evaluate 3 models, persist rows + predictions + audit."""
    is_baseline = technique == C.BASELINE
    slug = C.BASELINE_SLUG if is_baseline else C.TECHNIQUE_SLUGS[technique]
    per_csv = Path(results_csv) if is_baseline else out / f"results_{slug}.csv"
    pred_path = out / f"test_predictions_{slug}.parquet"
    audit_path = out / "audit.json"
    dist_path = out / "class_distributions.json"
    ckpt_path = out / "checkpoint.json"
    log_path = out / "run.log"

    # --- resume logic ---------------------------------------------------------
    pairs = C.completed_pairs(results_csv)
    complete = all((technique, m) in pairs for m in C.MODELS) and pred_path.exists()
    if complete and not force:
        C.log(f"[skip] {technique}: all 3 models + predictions already present", log_path)
        return
    if not force and any((technique, m) in pairs for m in C.MODELS):
        C.log(f"[resume] {technique}: incomplete set found -- dropping partial rows", log_path)
        C.drop_technique_rows(results_csv, technique)

    C.log(f"\n=== {technique} === [{C.rss_gb()} GB RSS]", log_path)
    yt = np.asarray(yte).ravel()

    # --- choose train source --------------------------------------------------
    # SVM-SMOTE / SMOTE-N are O(n^2) and run on the shared stratified 50k
    # subsample (regenerated by 01_prepare_p2.py from the corrected train split).
    if technique in SUBSAMPLE_TECHNIQUES:
        Xsub = pd.read_parquet(out / "subsample_X_50k.parquet")
        ysub = pd.read_parquet(out / "subsample_y_50k.parquet")["y"].astype(np.int64)
        Xsrc, ysrc = Xsub.values.astype(np.int64, copy=False), ysub.values
        assert len(Xsrc) == 50_000, f"subsample size {len(Xsrc)}"
        train_source = "shared stratified 50k subsample"
        C.log(f"  train source: {train_source} {Xsrc.shape} {C.class_counts(ysrc)}", log_path)
    else:
        Xsrc, ysrc = np.asarray(Xtr), np.asarray(ytr).ravel()
        train_source = ("full corrected train split (1,837,734 rows)" if not is_baseline
                        else "raw corrected train split (no resampling)")

    # --- resample (train only) ------------------------------------------------
    if is_baseline:
        Xr, yr = Xsrc, ysrc
        resample_sec = 0.0
        C.log("  baseline: no resampling", log_path)
    else:
        sampler = C.make_resampler(technique)
        t = time.perf_counter()
        Xr, yr = sampler.fit_resample(Xsrc, ysrc)
        resample_sec = time.perf_counter() - t
        Xr = np.asarray(Xr).astype(np.int64, copy=False)
        yr = np.asarray(yr).astype(np.int64, copy=False)
        C.log(f"  resampled in {resample_sec:.1f}s | {len(Xsrc):,} -> {len(Xr):,} | "
              f"{C.class_counts(yr)}", log_path)

    # --- audit + class distributions -----------------------------------------
    audit = C.audit_resample(technique, Xsrc, ysrc, Xr, yr, C.FEATURES)
    audit["resample_sec"] = round(resample_sec, 1)
    audit["scaled_on"] = "resampled train (LogisticRegression only)"
    audit["train_source"] = train_source
    audits = C.load_json(audit_path, {}) or {}
    audits[technique] = audit
    C.save_json(audit_path, audits)

    dists = C.load_json(dist_path, {}) or {}
    dists[technique] = {
        "technique": technique,
        "train_source": train_source,
        "train_before": audit["train_before"],
        "train_after": audit["train_after"],
        "added_samples": audit["added_samples"],
        "final_train_size": audit["final_train_size"],
        "rows_removed": audit["rows_removed"],
        "resample_sec": round(resample_sec, 1),
    }
    C.save_json(dist_path, dists)

    # --- models ---------------------------------------------------------------
    rows, pred_store = [], {"y_true": yt.astype(np.int64)}
    for name, (kind, model) in C.make_models().items():
        t = time.perf_counter()
        if kind == "scaled":
            scaler = StandardScaler().fit(Xr)
            Xf = scaler.transform(Xr)
            Xt = scaler.transform(np.asarray(Xte))
            model.fit(Xf, yr)
            pred = model.predict(Xt)
            proba = model.predict_proba(Xt)[:, 1]
            del Xf, Xt
        else:
            model.fit(Xr, yr)
            pred = model.predict(np.asarray(Xte))
            proba = model.predict_proba(np.asarray(Xte))[:, 1]
        dt = time.perf_counter() - t

        metrics = C.compute_metrics(yt, pred, proba)
        assert metrics["TN"] + metrics["FP"] + metrics["FN"] + metrics["TP"] == len(yt)
        assert all(np.isfinite(metrics[k]) and 0.0 <= metrics[k] <= 1.0
                   for k in ["Accuracy", "Precision", "Recall", "F1", "ROC_AUC", "PR_AUC"])
        row = C.format_result_row(technique, name, metrics, dt)
        C.append_result_row(results_csv, row)
        rows.append(row)
        pred_store[f"{name}__pred"] = pred.astype(np.int8)
        pred_store[f"{name}__proba"] = proba.astype(np.float32)
        C.log(f"  {name}: F1={metrics['F1']:.4f} Recall={metrics['Recall']:.4f} "
              f"ROC-AUC={metrics['ROC_AUC']:.4f} [{dt:.1f}s] [{C.rss_gb()} GB RSS]", log_path)
        del model

    # --- per-technique CSV (P1 style) ----------------------------------------
    lines = [C.RESULTS_HEADER] + [ln for ln in rows]
    per_csv.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # --- predictions parquet (atomic) ---------------------------------------
    assert len(pred_store) == 1 + 2 * len(C.MODELS), "incomplete prediction store"
    df = pd.DataFrame(pred_store)
    tmp = pred_path.with_name(pred_path.name + ".tmp")
    df.to_parquet(tmp, index=False)
    os.replace(tmp, pred_path)
    assert (df["y_true"].values == yt).all(), "y_true drift"
    C.log(f"  wrote {pred_path.name} ({len(df):,} rows x {df.shape[1]} cols)", log_path)

    # --- checkpoint ----------------------------------------------------------
    ckpt = C.load_json(ckpt_path, {}) or {}
    done = set(ckpt.get("completed_techniques", []))
    if all((technique, m) in C.completed_pairs(results_csv) for m in C.MODELS):
        done.add(technique)
    ckpt.update({
        "completed_techniques": sorted(done),
        "test_fingerprint": C.fingerprint(np.asarray(Xte), yt),
        "updated_at_utc": C.environment_record()["recorded_at_utc"],
    })
    C.save_json(ckpt_path, ckpt)
    C.release(Xr, yr)


def determinism_check(Xtr, ytr, out):
    """Resample every technique twice; require identical arrays."""
    C.log("=== determinism check (each resampler run twice) ===", out / "run.log")
    ok = True
    report = {}
    for tech in C.TECHNIQUES:
        sampler = C.make_resampler(tech)
        X1, y1 = sampler.fit_resample(np.asarray(Xtr), np.asarray(ytr).ravel())
        sampler = C.make_resampler(tech)
        X2, y2 = sampler.fit_resample(np.asarray(Xtr), np.asarray(ytr).ravel())
        fp1, fp2 = C.fingerprint(X1, y1), C.fingerprint(X2, y2)
        same = fp1 == fp2
        ok &= same
        report[tech] = {"identical": bool(same), "fingerprint_run1": fp1,
                        "fingerprint_run2": fp2, "class_counts": C.class_counts(y1),
                        "final_train_size": int(len(y1))}
        C.log(f"  {tech}: {'IDENTICAL' if same else 'DIFFERENT'} "
              f"({C.class_counts(y1)})", out / "run.log")
        del X1, y1, X2, y2
        C.release()
    C.save_json(out / "determinism.json", {"pass": bool(ok), "techniques": report})
    C.log(f"=== determinism: {'PASS' if ok else 'FAIL'} ===", out / "run.log")
    return ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pilot", action="store_true", help="run on a 100k pilot sample")
    ap.add_argument("--determinism", action="store_true", help="resample twice, compare")
    ap.add_argument("--force", action="store_true", help="redo completed work")
    ap.add_argument("--no-baseline", action="store_true")
    ap.add_argument("--techniques", nargs="*", default=None, choices=C.TECHNIQUES)
    args = ap.parse_args()

    out = (C.BASE / "pilot" / "results") if args.pilot else (C.BASE / "results")
    out.mkdir(parents=True, exist_ok=True)
    log_path = out / "run.log"

    Xtr, ytr, Xte, yte, fp, note = load_data(args.pilot)
    C.log(f"=== P2 experiments ({note}) ===", log_path)
    C.log(f"  train {Xtr.shape} {C.class_counts(ytr)} | test {Xte.shape} {C.class_counts(yte)}", log_path)
    C.log(f"  test fingerprint {fp}", log_path)

    if args.pilot:
        C.save_json(out / "pilot_split.json", {
            "note": note, "train_rows": int(len(Xtr)), "test_rows": int(len(Xte)),
            "train_counts": C.class_counts(ytr), "test_counts": C.class_counts(yte),
            "test_fingerprint": fp, "seed": C.RNG,
        })

    if args.determinism:
        ok = determinism_check(Xtr, ytr, out)
        sys.exit(0 if ok else 1)

    if not args.no_baseline:
        baseline_csv = out / "results_baseline_no_balancing.csv"
        run_technique(C.BASELINE, Xtr, ytr, Xte, yte, out, baseline_csv, args.force)

    techniques = args.techniques if args.techniques else C.TECHNIQUES
    results_csv = out / "results_person2.csv"
    for tech in techniques:
        run_technique(tech, Xtr, ytr, Xte, yte, out, results_csv, args.force)

    # --- final integrity checks ---------------------------------------------
    if not args.pilot:
        on_disk = verify_on_disk_fingerprint()
        if on_disk != C.EXPECTED_TEST_FINGERPRINT:
            raise SystemExit("TEST SET CHANGED ON DISK DURING RUN")
        C.log("  post-run test fingerprint verified on disk", log_path)

    n_expected = 3 * len(techniques)
    pairs = C.completed_pairs(results_csv)
    C.log(f"=== complete: {len(pairs)} / {n_expected} (technique, model) rows ===", log_path)
    if len(pairs) != n_expected:
        C.log("  WARNING: results_person2.csv is incomplete", log_path)


if __name__ == "__main__":
    main()
